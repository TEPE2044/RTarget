-- ============================================================
-- 0012: 删除无人使用的物化视图 vitality_current
--
-- 为什么删（三条，前两条是"没用"，第三条是"有害"）：
--   1) 全项目没有任何地方读它。前端 getVitality() 是直接
--      sum(vitality_ledger.amount)，压根不走这个视图。
--   2) 也没有任何地方 refresh 它。物化视图不自动跟着数据变，
--      所以它从创建那一刻起就是旧数字 —— 留着只会误导以后查库的人。
--   3) 它会挡住 vitality_ledger 的结构变更：0007 把 amount 改成 integer 时，
--      就因为视图依赖这一列，必须先 drop 视图再重建，白白多绕一圈。
--
-- 当初的意图是给"当前活力值"做一层缓存（0001 的注释写着"可随时重建"），
-- 但流水求和本身很轻，缓存没接上，于是就成了纯负担。
--
-- 幂等：带 if exists，重复执行不报错。
-- ============================================================

drop materialized view if exists vitality_current;
